//! Android board support.
//!
//! The mirror of `platform/linux`: same renderer, same core, different
//! lifecycle. Android's is the awkward one, and the two differences that
//! matter are both here rather than leaking upward:
//!
//! * **The surface comes and goes.** On Linux a window exists from startup to
//!   exit. On Android the activity is told to release its surface whenever it
//!   is backgrounded, and gets a new one on return — so the renderer is
//!   built in `resumed` and dropped in `suspended`, and `View` outlives both.
//!   That is why the view state lives in the core and not in the renderer.
//!
//! * **There is no `main`.** `android_main` is called by the NDK's glue after
//!   the JVM has started, and the `#[no_mangle]` entry point is generated by
//!   the `android_main` attribute macro.
//!
//! Status: this compiles and cross-links for aarch64-linux-android, which
//! `rutter android` verifies. It has not been run on a device, because there
//! is no APK to put it in yet — see README.md.

// Off-Android, nothing reaches `App` because `android_main` is the only
// caller and it is compiled on Android alone. It is still *built* everywhere
// on purpose — type-checking this file on the laptop, without waiting for a
// cross-compile, is most of the value of having it in Rust at all.
#![cfg_attr(not(target_os = "android"), allow(dead_code))]

#[cfg(target_os = "android")]
use winit::platform::android::activity::AndroidApp;

// The only unsafe thing in the project, and unavoidable: the NDK's glue
// finds this entry point by symbol name, so it cannot be mangled. Spelled
// with the explicit `unsafe(…)` form and an `allow` rather than relaxing the
// workspace lint, so the one exception stays visible in review.
#[cfg(target_os = "android")]
#[allow(unsafe_code)]
#[unsafe(no_mangle)]
fn android_main(app: AndroidApp) {
    use winit::event_loop::EventLoop;
    use winit::platform::android::EventLoopBuilderExtAndroid;

    android_logger::init_once(
        android_logger::Config::default()
            .with_max_level(log::LevelFilter::Info)
            .with_tag("rutter"),
    );

    log::info!("rutter starting");

    // Charts must come off the asset store before the event loop takes the
    // AndroidApp.
    let charts = open_bundled_chart(&app);

    let event_loop = match EventLoop::builder().with_android_app(app).build() {
        Ok(el) => el,
        Err(e) => {
            log::error!("could not build the event loop: {e}");
            return;
        }
    };

    let mut state = App {
        charts,
        ..App::default()
    };
    if let Err(e) = event_loop.run_app(&mut state) {
        log::error!("event loop ended: {e}");
    }
}

/// Copy the chart bundled in the APK to internal storage, then open it.
///
/// The copy is not avoidable. An asset is a zip entry inside the APK, and
/// SQLite needs a real file it can seek within — so the first run pays for
/// one copy and every run after it finds the file already there.
///
/// Returns `None` on any failure. A missing or unreadable chart should leave
/// the app drawing an empty grid, not refuse to start: on a boat, an app that
/// opens with no chart is still a compass, and one that will not open is
/// nothing.
#[cfg(target_os = "android")]
fn open_bundled_chart(app: &AndroidApp) -> Option<ChartSource> {
    use std::ffi::CString;
    use std::io::Read;

    const ASSET: &str = "coast.mbtiles";

    let dir = app.internal_data_path()?;
    let path = dir.join(ASSET);

    if !path.exists() {
        log::info!("extracting {ASSET} to {}", path.display());

        let name = CString::new(ASSET).ok()?;
        let mut asset = app.asset_manager().open(&name)?;

        let mut bytes = Vec::new();
        if let Err(e) = asset.read_to_end(&mut bytes) {
            log::error!("reading asset {ASSET}: {e}");
            return None;
        }

        if let Err(e) = std::fs::create_dir_all(&dir) {
            log::error!("creating {}: {e}", dir.display());
            return None;
        }

        // Write via a temporary name and rename, so a run interrupted
        // mid-copy does not leave a truncated database that then looks
        // present and fails to open on every launch afterwards.
        let partial = path.with_extension("partial");
        if let Err(e) = std::fs::write(&partial, &bytes) {
            log::error!("writing {}: {e}", partial.display());
            return None;
        }
        if let Err(e) = std::fs::rename(&partial, &path) {
            log::error!("renaming into place: {e}");
            return None;
        }
        log::info!("extracted {} bytes", bytes.len());
    }

    match ChartSource::open(&path, &[]) {
        Ok(source) => {
            let meta = source.metadata();
            log::info!(
                "charts: {} zoom {}..{}",
                if meta.name.is_empty() {
                    ASSET
                } else {
                    &meta.name
                },
                meta.min_zoom,
                meta.max_zoom
            );
            Some(source)
        }
        Err(e) => {
            log::error!("opening {}: {e}", path.display());
            None
        }
    }
}

// The app itself is target-independent; only the entry point above is not.
// Compiled on every target so that `cargo check` on the laptop still type-checks
// it, which is most of the value of having it in Rust.

use std::sync::Arc;

use rutter_charts::ChartSource;
use rutter_core::chart::TileId;
use rutter_core::{chart, LatLon, View};
use rutter_render::{Frame, Renderer};
use winit::application::ApplicationHandler;
use winit::event::{ElementState, TouchPhase, WindowEvent};
use winit::event_loop::ActiveEventLoop;
use winit::window::{Window, WindowId};

#[derive(Default)]
struct App {
    window: Option<Arc<Window>>,
    renderer: Option<Renderer>,
    view: View,
    /// Where the active finger was last seen, for one-finger panning.
    finger: Option<(f64, f64)>,
    charts: Option<ChartSource>,
    /// The tile set the renderer's chart buffer was built from. Panning
    /// within one tile — most of a drag — must not re-decode geometry that
    /// is already on the GPU.
    loaded: Vec<TileId>,
}

impl App {
    fn pan_pixels(&mut self, dx: f64, dy: f64) {
        let pixels_per_world = 256.0 * 2f64.powf(self.view.zoom);
        let mut w = chart::project(self.view.centre);
        w.x = (w.x - dx / pixels_per_world).clamp(0.0, 1.0);
        w.y = (w.y - dy / pixels_per_world).clamp(0.0, 1.0);
        self.view.centre = chart::unproject(w);
    }

    /// Reload chart geometry if the visible tile set has changed.
    ///
    /// Deliberately the same shape as the Linux shim's, and deliberately
    /// thin: the work of picking tiles and gathering geometry is in
    /// `rutter-charts`, where it is written once and tested without a device.
    fn refresh_charts(&mut self) {
        let Some(source) = self.charts.as_mut() else {
            return;
        };
        let Some(renderer) = self.renderer.as_mut() else {
            return;
        };

        let got = source.collect(&self.view);
        if got.tiles == self.loaded {
            return;
        }

        if let Some(wanted) = got.over_budget {
            log::debug!("charts: {wanted} tiles wanted, over budget — not drawing");
            renderer.clear_chart();
            self.loaded = got.tiles;
            return;
        }

        for (id, why) in &got.failed {
            log::warn!("{id:?}: {why}");
        }

        renderer.set_chart(&got.line_slices(), &got.points);
        log::debug!(
            "charts: {} tiles, {} polylines, {} points",
            got.tiles.len(),
            got.lines.len(),
            got.points.len()
        );

        self.loaded = got.tiles;
    }
}

impl ApplicationHandler for App {
    fn resumed(&mut self, event_loop: &ActiveEventLoop) {
        let window = match event_loop.create_window(Window::default_attributes()) {
            Ok(w) => Arc::new(w),
            Err(e) => {
                log::error!("no window: {e}");
                return;
            }
        };

        let size = window.inner_size();
        self.view.width_px = size.width.max(1);
        self.view.height_px = size.height.max(1);

        // Open on the chart, so the first launch shows data rather than
        // empty sea somewhere else. Only on the first resume: coming back
        // from the background should return to where the user was.
        if self.loaded.is_empty() {
            if let Some(source) = &self.charts {
                if let Some(b) = source.metadata().bounds {
                    self.view.centre = LatLon::new((b[1] + b[3]) / 2.0, (b[0] + b[2]) / 2.0);
                    self.view.zoom = f64::from(source.metadata().max_zoom);
                }
            }
        }

        match pollster::block_on(Renderer::new(window.clone(), size.width, size.height)) {
            Ok(r) => self.renderer = Some(r),
            Err(e) => {
                log::error!("no renderer: {e}");
                return;
            }
        }

        self.window = Some(window);
    }

    fn suspended(&mut self, _event_loop: &ActiveEventLoop) {
        // Both must go, and in this order: the surface borrows the window, so
        // keeping the renderer across a suspend is a use-after-free waiting
        // for the next resume.
        log::info!("suspending; releasing the surface");
        self.renderer = None;
        self.window = None;
        self.finger = None;
        // Same reason as above: the uploaded geometry went with the renderer.
        // The ChartSource and its decoded-tile cache survive, so coming back
        // costs an upload but not a re-decode.
        self.loaded.clear();
    }

    fn window_event(&mut self, event_loop: &ActiveEventLoop, _id: WindowId, event: WindowEvent) {
        match event {
            WindowEvent::CloseRequested => event_loop.exit(),

            WindowEvent::Resized(size) => {
                self.view.width_px = size.width.max(1);
                self.view.height_px = size.height.max(1);
                if let Some(r) = self.renderer.as_mut() {
                    r.resize(size.width, size.height);
                }
            }

            WindowEvent::Touch(touch) => {
                let now = (touch.location.x, touch.location.y);
                match touch.phase {
                    TouchPhase::Started => self.finger = Some(now),
                    TouchPhase::Moved => {
                        if let Some(last) = self.finger {
                            self.pan_pixels(now.0 - last.0, now.1 - last.1);
                            if let Some(w) = &self.window {
                                w.request_redraw();
                            }
                        }
                        self.finger = Some(now);
                    }
                    TouchPhase::Ended | TouchPhase::Cancelled => self.finger = None,
                }
            }

            // Pinch-to-zoom is the obvious gap. winit reports raw touch
            // points on Android rather than a scale gesture, so it means
            // tracking two ids and their separation. Deliberately left until
            // there is a device to tune it on — guessing at gesture
            // thresholds without one is how you get a chart that fights you.
            WindowEvent::KeyboardInput { event, .. } if event.state == ElementState::Pressed => {
                log::debug!("key {:?}", event.logical_key);
            }

            WindowEvent::RedrawRequested => {
                self.refresh_charts();

                let Some(renderer) = self.renderer.as_mut() else {
                    return;
                };
                match renderer.render(&self.view) {
                    Frame::Drawn | Frame::Skipped => {}
                    Frame::Reconfigured => {
                        if let Some(w) = &self.window {
                            w.request_redraw();
                        }
                    }
                    // Routine here, unlike on Linux: it is what Android does
                    // on the way out. `resumed` builds a new one.
                    Frame::SurfaceLost => {
                        log::info!("surface lost; waiting for resume");
                        self.renderer = None;
                        self.window = None;
                        // The chart buffer died with the renderer, so the
                        // record of what was uploaded is now a lie.
                        self.loaded.clear();
                    }
                }
            }

            _ => {}
        }
    }
}
